echo "----------------------------------------"
echo "  IP              MAC               TYPE"
echo "----------------------------------------"

echo "$SCAN_RESULT" | while read -r line; do
    if [ -z "$line" ] || echo "$line" | grep -qE "^(Interface|Starting|Ending|packets received|$)"; then
        continue
    fi
    
    if echo "$line" | grep -qE '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+'; then
        IP=$(echo "$line" | awk '{print $1}')
        MAC=$(echo "$line" | awk '{print $2}')
        VENDOR=$(echo "$line" | cut -d' ' -f3- | sed 's/^ *//')
        
        TYPE=$(detect_type "$MAC" "$VENDOR")
        
        if echo "$line" | grep -q "DUP"; then
            continue
        fi
        
        printf "  %-15s %-17s %s\n" "$IP" "$MAC" "$TYPE"
    fi
done

