IP=$(echo "$IP_MASK" | cut -d/ -f1)
MASK=$(echo "$IP_MASK" | cut -d/ -f2)

get_network_address() {
    local ip="$1"
    local mask="$2"
    IFS=. read -r a b c d <<< "$ip"
    local shift=$((32 - mask))
    local net=$(( (a << 24) + (b << 16) + (c << 8) + d ))
    net=$(( (net >> shift) << shift ))
    echo "$(( (net >> 24) & 255 )).$(( (net >> 16) & 255 )).$(( (net >> 8) & 255 )).$(( net & 255 ))/$mask"
}

NETWORK=$(get_network_address "$IP" "$MASK")

if [ -z "$NETWORK" ]; then
    echo "[ОШИБКА] Не удалось вычислить адрес сети"
